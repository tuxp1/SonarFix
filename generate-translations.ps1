# Generated outputs are checked in for direct ISCC use, rebuilt from one catalog.
$catalog=Get-Content -Raw -Encoding UTF8 (Join-Path $PSScriptRoot 'localization\strings.json') | ConvertFrom-Json
$lines=[System.Collections.Generic.List[string]]::new()
$lines.Add('// Generated by generate-translations.ps1; edit localization/strings.json.')
$lines.Add('function Tr(Key: String): String;')
$lines.Add('begin')
foreach($p in $catalog.PSObject.Properties){
    $en=$p.Value.en.Replace("'","''");$ar=$p.Value.ar.Replace("'","''")
    $lines.Add("  if Key = '$($p.Name)' then begin Result := Txt('$en', '$ar'); Exit; end;")
}
$lines.Add("  RaiseException('Missing translation: '+Key); Result := ''; ")
$lines.Add('end;')
$lines | Set-Content -Encoding UTF8 (Join-Path $PSScriptRoot 'installer\Translations.iss')
